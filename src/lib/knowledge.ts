    tenant_rights: ["landlord", "tenant", "rent", "deposit", "eviction", "house owner", "lease", "rental", "makan", "kirayedar", "security deposit", "paying guest"],
    workplace_rights: ["salary", "employer", "fired", "terminated", "wages", "pf", "provident", "workplace", "job", "labour", "labor", "maternity", "gratuity", "epfo", "retrenchment", "notice period", "sexual harassment", "posh", "icc"],
